// Build-time tool only. The macOS app reads the generated ICS offline.
const fs = require('node:fs')
const path = require('node:path')
const { createHash } = require('node:crypto')
const Holidays = require('date-holidays-parser').default
const { CalendarVietnamese } = require('date-chinese')
const yaml = require('js-yaml')
const source = require('./source.json')

const outputPath = path.resolve(__dirname, '../../App/Resources/Holidays/vietnam.ics')
const hash = value => createHash('sha256').update(value).digest('hex')

function directLunarDate (rule, year) {
  const match = /^(?:(\d+) day before )?vietnamese (\d+)-0-(\d+)$/.exec(rule)
  if (!match) return null // Solar dates and solar terms remain with the parser.
  const [, before = '0', month, day] = match
  const candidates = []
  for (const lunarYear of [year - 1, year]) {
    const calendar = new CalendarVietnamese()
    calendar.set(undefined, undefined, Number(month), false, Number(day))
    // The parser's toJDE -> fromJDE -> toGregorian round-trip truncates a
    // fractional day in date-chinese 2.1.4 (e.g. 23/12/2039 becomes 22/12).
    // Direct conversion retains the requested lunar day; never patch dates.
    const civil = calendar.toGregorian(lunarYear)
    const date = new Date(Date.UTC(civil.year, civil.month - 1, civil.day - Number(before)))
    if (date.getUTCFullYear() === year) candidates.push(date.toISOString().slice(0, 10).replaceAll('-', ''))
  }
  if (candidates.length !== 1) throw new Error(`Ambiguous lunar rule: ${rule} in ${year}`)
  return candidates[0]
}

function getEvents () {
  for (const [file, expected] of Object.entries(source.sha256)) {
    if (hash(fs.readFileSync(path.join(__dirname, 'vendor', file))) !== expected) {
      throw new Error(`Source checksum mismatch: ${file}`)
    }
  }
  const country = yaml.load(fs.readFileSync(path.join(__dirname, 'vendor/VN.yaml'), 'utf8'))
  const names = JSON.parse(fs.readFileSync(path.join(__dirname, 'vendor/names.json'), 'utf8'))
  const holidays = new Holidays({ ...country, ...names }, 'VN', null, null, {
    languages: ['vi'], timezone: 'Asia/Ho_Chi_Minh'
  })
  const events = []
  for (let year = source.startYear; year <= source.endYear; year++) {
    for (const holiday of holidays.getHolidays(year)) {
      if (Object.hasOwn(source.excludedRules, holiday.rule)) continue
      // Use the library's civil date, never the UTC date of its Date objects.
      const date = directLunarDate(holiday.rule, year) ?? holiday.date.slice(0, 10).replaceAll('-', '')
      const dayCount = (holiday.end - holiday.start) / 86400000
      if (!holiday.date.endsWith(' 00:00:00') || Number(date.slice(0, 4)) !== year) {
        throw new Error(`Unsupported holiday date: ${holiday.date}`)
      }
      events.push({ date, name: holiday.name, type: holiday.type, dayCount, rule: holiday.rule })
    }
  }
  // A fixed lexical order avoids OS locale affecting generated bytes.
  return events.sort((a, b) => {
    const left = `${a.date}:${a.rule}`
    const right = `${b.date}:${b.rule}`
    return left < right ? -1 : left > right ? 1 : 0
  })
}

function escapeText (text) {
  return text.replaceAll('\\', '\\\\').replace(/\r\n|\r|\n/g, '\\n')
    .replaceAll(';', '\\;').replaceAll(',', '\\,')
}

// RFC 5545 folds at 75 octets, including the continuation space. Iterate
// Unicode code points so a Vietnamese UTF-8 character is never split.
function fold (line) {
  let result = ''
  let bytes = 0
  for (const character of line) {
    const size = Buffer.byteLength(character)
    if (bytes + size > 75) {
      result += '\r\n '
      bytes = 1
    }
    result += character
    bytes += size
  }
  return result
}

function serializeCalendar (events) {
  const lines = [
    'BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//VietLunar//Vietnam Holidays//VI',
    'CALSCALE:GREGORIAN', 'X-WR-CALNAME:Lễ và ngày kỷ niệm Việt Nam (2000–2050)',
    'X-WR-TIMEZONE:Asia/Ho_Chi_Minh',
    `X-WR-CALDESC:${escapeText(`${source.attribution}; ${source.attributionURL}; ${source.repository}/tree/${source.commit}; Data: CC BY-SA 3.0 https://creativecommons.org/licenses/by-sa/3.0/; Adapted: projected leave periods excluded; direct lunar conversion avoids parser round-trip truncation. Dates follow source rules, not a historical or employer leave record.`)}`,
    `X-VIETLUNAR-SOURCE-COMMIT:${source.commit}`
  ]
  const ids = new Set()
  for (const event of events) {
    if (!['public', 'observance'].includes(event.type)) throw new Error(`Unsupported type: ${event.type}`)
    if (event.dayCount !== 1) throw new Error(`Review multi-day rule before publishing: ${event.rule}`)
    if (!/^\d{8}$/.test(event.date) || !event.name) throw new Error('Invalid event')
    const uid = `${hash(`${event.rule}:${event.date}`).slice(0, 32)}@vietlunar`
    if (ids.has(uid)) throw new Error(`Duplicate event: ${event.rule} ${event.date}`)
    ids.add(uid)
    lines.push(
      'BEGIN:VEVENT', `UID:${uid}`,
      `DTSTAMP:${source.snapshotDate.replaceAll('-', '')}T000000Z`,
      `SUMMARY:${escapeText(event.name)}`, `DTSTART;VALUE=DATE:${event.date}`,
      'DURATION:P1D', `DESCRIPTION:${event.type}`, 'END:VEVENT'
    )
  }
  lines.push('END:VCALENDAR')
  const text = lines.map(fold).join('\r\n') + '\r\n'
  if (events.length > 20000 || Buffer.byteLength(text) > 1048576) {
    throw new Error('Calendar exceeds app parser limits')
  }
  return text
}

function generateCalendar () {
  return serializeCalendar(getEvents())
}

if (require.main === module) {
  try {
    const args = process.argv.slice(2)
    if (args.length && (args.length !== 1 || args[0] !== '--check')) {
      throw new Error('Usage: node generate.cjs [--check]')
    }
    const text = generateCalendar()
    if (args[0] === '--check') {
      if (fs.readFileSync(outputPath, 'utf8') !== text) throw new Error('Bundled ICS is stale; run npm run generate in Tools/Holidays')
      console.log('Bundled holiday ICS matches pinned source and generator.')
    } else {
      fs.writeFileSync(outputPath, text)
      console.log(`Generated ${outputPath} (${Buffer.byteLength(text)} bytes)`)
    }
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}

module.exports = { getEvents, serializeCalendar, generateCalendar }
